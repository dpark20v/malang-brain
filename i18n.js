  let lang = 'ko';

  /* 저장된 언어 → 없으면 브라우저 언어 → 없으면 한국어 */
  function detect() {
    try {
      const saved = JSON.parse(localStorage.getItem('malang:pref:lang'));
      if (saved && DICT[saved]) return saved;
    } catch (e) {}
    const nav = (navigator.language || 'ko').toLowerCase();
    if (nav.indexOf('ko') === 0) return 'ko';
    if (nav.indexOf('ja') === 0) return 'ja';
    if (nav.indexOf('zh') === 0) return 'zh';
    if (nav.indexOf('en') === 0) return 'en';
    return 'ko';
  }

  /* 글자 하나 가져오기. {name} 같은 자리는 vars 로 채웁니다. */
  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]);
    if (s === undefined) s = DICT.ko[key];       // 빠진 번역은 한국어로 대체
    if (s === undefined) return key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.split('{' + k + '}').join(vars[k]);
      });
    }
    return s;
  }

  /* 화면에 표시된 글자를 현재 언어로 갈아 끼웁니다 */
  function apply(root) {
    const scope = root || document;

    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-ph')));
    });
    scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });

    if (!root) {
      document.documentElement.setAttribute('lang', lang);
      document.title = t('doc.title');
    }
  }

  function set(next) {
    if (!DICT[next]) return;
    lang = next;
    try { localStorage.setItem('malang:pref:lang', JSON.stringify(next)); } catch (e) {}
    apply();
    /* app.js 가 만들어 둔 화면도 다시 그리도록 알려 줍니다 */
    window.dispatchEvent(new CustomEvent('malang:langchange', { detail: next }));
  }

  lang = detect();

  /* ---- 전역으로 노출 ---- */
  window.MALANG_I18N = {
    LANGS: LANGS,
    DICT: DICT,
    t: t,
    apply: apply,
    set: set,
    get: function () { return lang; }
  };
  window.t = t;      // app.js 에서 짧게 쓰기 위해

  /* HTML 이 준비되는 대로 한 번 적용 */
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', function () { apply(); });
  } else {
    apply();
  }
